"""NIFTY 50 ORB Stock Scanner and Signal REST endpoints."""

from datetime import datetime
from typing import List, Optional
from fastapi import APIRouter, Depends, Query, status
from sqlalchemy import desc, func, select
from sqlalchemy.ext.asyncio import AsyncSession

from backend.app.database.session import get_db
from backend.app.models.instrument import Instrument
from backend.app.models.signal import TradingSignal
from backend.app.schemas.common import ApiResponse, PaginatedResponse
from backend.app.schemas.trading import (
    ScanCandidateResponse,
    ScannerSummaryResponse,
    SignalItemResponse,
)
from shared.market_time import now_ist
from trading_engine.scanner.orb_scanner import ORBScanner
from trading_engine.strategy.orb import ORBStrategy
from trading_engine.universe.nifty50 import get_nifty50_constituents

router = APIRouter(prefix="/scanner", tags=["Scanner & Signals"])
_scanner = ORBScanner(strategy=ORBStrategy())


@router.get(
    "",
    response_model=ApiResponse[ScannerSummaryResponse],
    status_code=status.HTTP_200_OK,
    summary="Scan NIFTY 50 Universe",
    description="Run or fetch current Opening Range Breakout (ORB) scan across active Nifty 50 equities.",
)
async def get_scanner_results() -> ApiResponse[ScannerSummaryResponse]:
    """Execute intraday ORB scan across Nifty 50 constituents."""
    current_date = now_ist().date()
    constituents = get_nifty50_constituents(current_date)
    raw_results = await _scanner.scan(universe=constituents, as_of_date=current_date)

    candidates = [ScanCandidateResponse(**r) for r in raw_results]
    triggered = sum(1 for c in candidates if c.status == "TRIGGERED")
    pending = sum(1 for c in candidates if c.status == "PENDING_BREAKOUT")
    forming = sum(1 for c in candidates if c.status == "RANGE_FORMING")

    summary = ScannerSummaryResponse(
        timestamp=now_ist(),
        universe_size=len(constituents),
        triggered_count=triggered,
        pending_count=pending,
        forming_count=forming,
        candidates=candidates,
    )
    return ApiResponse(success=True, data=summary)


@router.get(
    "/signals",
    response_model=ApiResponse[PaginatedResponse[SignalItemResponse]],
    status_code=status.HTTP_200_OK,
    summary="List Generated Signals",
    description="Retrieve historical strategy signals generated by the scanner.",
)
async def list_signals(
    page: int = Query(1, ge=1),
    page_size: int = Query(50, ge=1, le=100),
    status_filter: Optional[str] = Query(None, alias="status"),
    db: AsyncSession = Depends(get_db),
) -> ApiResponse[PaginatedResponse[SignalItemResponse]]:
    stmt = (
        select(TradingSignal, Instrument.symbol)
        .join(Instrument, TradingSignal.instrument_id == Instrument.id)
        .order_by(desc(TradingSignal.generated_at))
    )
    if status_filter:
        stmt = stmt.where(TradingSignal.status == status_filter.upper())

    count_stmt = select(func.count()).select_from(stmt.subquery())
    total = (await db.execute(count_stmt)).scalar() or 0

    paginated_stmt = stmt.offset((page - 1) * page_size).limit(page_size)
    rows = (await db.execute(paginated_stmt)).all()

    items = []
    for sig, sym in rows:
        item = SignalItemResponse(
            id=sig.id,
            instrument_id=sig.instrument_id,
            symbol=sym,
            strategy_name=sig.strategy_name,
            signal_type=sig.signal_type,
            trigger_price=float(sig.trigger_price),
            stop_loss=float(sig.stop_loss),
            target_price=float(sig.target_price),
            status=sig.status,
            rejection_reason=sig.rejection_reason,
            generated_at=sig.generated_at,
        )
        items.append(item)

    total_pages = (total + page_size - 1) // page_size if total > 0 else 0
    return ApiResponse(
        success=True,
        data=PaginatedResponse(
            items=items,
            total=total,
            page=page,
            page_size=page_size,
            total_pages=total_pages,
        ),
    )
